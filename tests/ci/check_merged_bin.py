#!/usr/bin/env python3
"""Verify that build/merged-firmware.bin really is the four flash images.

Why this exists
---------------
The firmware jobs used to upload "build/*.bin", which is a non-recursive glob.
It matched the application image and ota_data_initial.bin and missed
build/bootloader/bootloader.bin and build/partition_table/partition-table.bin
entirely, because those live in subdirectories. The artifact could therefore
update a board that was already running EzloPi, but could not bring up a blank
one -- and nothing said so. ESP Web Tools additionally will not accept a set of
separate images for an ESP-IDF v4 project: it wants one image flashed at offset
0. So the build now produces a merged image, and this script checks it.

What it checks
--------------
build/flash_args is generated by the build itself and holds the authoritative
"<offset> <file>" pairs, so neither this script nor the merge step restates any
offset and neither can drift from the partition table. For every pair, the
merged image must contain that file's bytes, unmodified, at that offset.

That is the entire correctness property of a merge, and checking it this way is
target-agnostic -- which matters, because the bootloader does not live at the
same place on every chip (0x1000 on ESP32 and ESP32-S2, 0x0 on ESP32-S3 and
ESP32-C3). A check with offsets written into it would have quietly passed on the
wrong thing for two of the four targets.

"esptool exited 0" is not a substitute. esptool is being asked to copy bytes to
offsets; the failure worth catching is a wrong offset or a missing input, and
both of those are successful esptool runs.
"""
import os
import sys

BUILD = sys.argv[1] if len(sys.argv) > 1 else "build"
MERGED = os.path.join(BUILD, "merged-firmware.bin")
FLASH_ARGS = os.path.join(BUILD, "flash_args")


def fail(msg):
    # The ::error:: prefix makes it an annotation on the run in the Actions UI,
    # not just a line somewhere in a 10000-line log.
    print("::error::%s" % msg)
    sys.exit(1)


def parse_flash_args(path):
    """Pull the <offset> <file> pairs out of build/flash_args.

    The file is one line of leading --flash_* options followed by alternating
    offsets and paths, e.g.

        --flash_mode dio --flash_freq 40m --flash_size 4MB
        0x1000 bootloader/bootloader.bin
        0x20000 Ezlo_Pi_v4x.bin

    esptool parses it with argparse's @file support, so the layout is whatever
    the build wrote. Anything that is not a 0x-prefixed token followed by a path
    is an option pair and is skipped, rather than assumed to be absent.
    """
    with open(path) as fh:
        tokens = fh.read().split()

    pairs, i = [], 0
    while i < len(tokens):
        tok = tokens[i]
        if tok.startswith("0x") and i + 1 < len(tokens):
            pairs.append((int(tok, 16), tokens[i + 1]))
            i += 2
        else:
            # A --flash_* option and its value, or a stray token. Not our
            # business, but do not silently treat it as an offset.
            i += 1
    return pairs


def main():
    for path in (MERGED, FLASH_ARGS):
        if not os.path.isfile(path):
            fail("%s does not exist; the merge step did not run or did not "
                 "produce an image." % path)

    pairs = parse_flash_args(FLASH_ARGS)
    if not pairs:
        fail("%s contained no '<offset> <file>' pairs. Parsing it wrongly would "
             "make this check vacuous, so that is a failure rather than a pass."
             % FLASH_ARGS)

    with open(MERGED, "rb") as fh:
        merged = fh.read()

    print("merged image: %s (%d bytes, 0x%x)" % (MERGED, len(merged), len(merged)))
    print("checking %d images listed in %s" % (len(pairs), FLASH_ARGS))

    problems = []
    for offset, rel in sorted(pairs):
        src = os.path.join(BUILD, rel)
        if not os.path.isfile(src):
            problems.append("0x%06x %s -- source image is missing" % (offset, rel))
            continue

        with open(src, "rb") as fh:
            want = fh.read()

        got = merged[offset:offset + len(want)]
        if len(got) < len(want):
            problems.append(
                "0x%06x %s -- merged image is only %d bytes, too short to hold "
                "%d bytes at this offset" % (offset, rel, len(merged), len(want)))
        elif got != want:
            # Report where it first diverges: "not equal" on a 1.7 MB image is
            # not enough to act on.
            first = next(i for i in range(len(want)) if got[i] != want[i])
            problems.append(
                "0x%06x %s -- contents differ, first at byte %d of the image "
                "(absolute 0x%x): merged has 0x%02x, source has 0x%02x"
                % (offset, rel, first, offset + first, got[first], want[first]))
        else:
            print("  ok      0x%06x  %-40s %7d bytes" % (offset, rel, len(want)))

    if problems:
        for p in problems:
            print("::error::merged image is wrong: %s" % p)
        fail("%d of %d images are not correctly placed in the merged image. "
             "Flashing it would brick or fail to boot." % (len(problems), len(pairs)))

    # A merge that dropped a trailing image would still pass every check above,
    # because every *listed* image would be present. The size is what catches
    # that: the merged image ends where the last image ends.
    last_off, last_rel = max(pairs)
    expect = last_off + os.path.getsize(os.path.join(BUILD, last_rel))
    if len(merged) != expect:
        fail("merged image is %d bytes but the last image (%s at 0x%x) ends at "
             "%d. Something was appended or truncated."
             % (len(merged), last_rel, last_off, expect))

    print("all %d images are byte-identical at their flash offsets; image ends "
          "exactly where %s does" % (len(pairs), last_rel))


if __name__ == "__main__":
    main()
